"""Настраиваемые параметры модели.

Все физические величины в СИ: ускорения в м/с^2, угловые скорости в рад/с,
углы в радианах, время в секундах. Значения подобраны эмпирически и
вынесены сюда, чтобы их можно было править без правки алгоритмов.
"""

from dataclasses import dataclass, field


@dataclass
class OrientationConfig:
    """Параметры оценки ориентации баллончика."""

    # Постоянная времени коррекции наклона по силе тяжести, с.
    # Коррекция применяется только когда баллончик почти неподвижен,
    # иначе она стягивала бы вертикаль обратно к центру прямо во время
    # ведения. Меньше значение - быстрее уходит дрейф, но заметнее
    # подтягивание после остановки руки.
    accel_tau: float = 1.0

    # Порог угловой скорости, ниже которого устройство считается
    # неподвижным и коррекция по силе тяжести включается, рад/с.
    # 0.12 рад/с - это около 7 градусов в секунду: дрожание руки сюда
    # попадает, а осознанное ведение уже нет, поэтому след не стягивает.
    accel_still_rate: float = 0.12

    # Порог отсечения шума гироскопа, рад/с (~0.6 град/с).
    gyro_deadzone: float = 0.010

    # Сколько пикселей холста приходится на один радиан поворота.
    # 700 px/рад при холсте 1600x900 означает, что холст занимает
    # сектор примерно +-65 градусов по горизонтали и +-37 по вертикали.
    # Больше значение - точнее мелкая работа, но меньше рабочий сектор.
    px_per_rad: float = 700.0

    # Поворот хвата в градусах: насколько геймпад повёрнут в руке
    # относительно обычного положения. При 90 поворот геймпада вправо
    # уводит след вверх, вверх - влево, влево - вниз, вниз - вправо,
    # что соответствует хвату "как баллончик" одной рукой.
    # Допустимые значения: 0, 90, 180, 270. В приложении меняется
    # клавишей G без перезапуска.
    grip_rotation: float = 90.0

    # Скорость самостоятельного возврата точки к центру, рад/с.
    # Возврат сильный, поэтому включается только после auto_center_delay
    # секунд без использования органов управления (рисование, палитра,
    # размер сопла и прочие кнопки). 0 отключает возврат.
    auto_center_rate: float = 1.5
    auto_center_delay: float = 10.0

    # Число выборок, усредняемых при калибровке нулевого положения.
    calibration_samples: int = 180

    # Допустимый разброс показаний гироскопа при калибровке, рад/с.
    # Если баллончик в это время двигали, калибровка отклоняется.
    calibration_tolerance: float = 0.35


@dataclass
class ShakeConfig:
    """Параметры детектора встряхивания и модели перемешивания краски."""

    # Порог линейного ускорения вдоль оси баллончика, при котором
    # движение считается взмахом, м/с^2.
    accel_threshold: float = 6.0

    # Минимальный и максимальный интервал между сменами направления.
    # Слишком частые смены - дребезг, слишком редкие - уже не встряхивание.
    min_stroke_interval: float = 0.07
    max_stroke_interval: float = 0.80

    # Прирост уровня перемешивания за один взмах.
    # 0.085 означает, что для полного перемешивания нужно около 12 взмахов.
    mix_per_stroke: float = 0.085

    # Убывание уровня перемешивания: доля в секунду.
    # Краска расслаивается сама по себе и дополнительно расходуется
    # пигмент при распылении.
    idle_decay: float = 1.0 / 240.0
    spray_decay: float = 0.018

    # Пороги качества.
    good_mix: float = 0.75   # выше - краска ложится ровно
    warn_mix: float = 0.30   # ниже - предупреждение в интерфейсе
    clog_mix: float = 0.12   # ниже - баллончик плюётся вместо распыления

    # Длительность отдачи вибромотора на один взмах, мс.
    rumble_ms: int = 55


@dataclass
class SprayConfig:
    """Параметры сопла и модели распыления."""

    base_radius: float = 38.0
    min_radius: float = 6.0
    max_radius: float = 170.0

    # Жёсткость края: 0 - размытое облако, 1 - почти резкая граница.
    hardness: float = 0.45

    # Подача краски при полностью нажатом курке, доля в секунду.
    flow: float = 1.0

    # Шаг между отпечатками вдоль следа, в долях радиуса.
    # Меньше - плавнее след, но дороже по времени.
    spacing_ratio: float = 0.12

    # Насколько удаление от холста увеличивает пятно.
    # Радиус умножается на (1 + distance_gain * distance).
    distance_gain: float = 0.9

    # Прозрачность одного отпечатка в центре при идеальных условиях.
    alpha_per_stamp: float = 0.055

    # Порог влажности, после которого краска начинает течь.
    drip_threshold: float = 1.8
    drip_chance: float = 0.5
    max_drips: int = 48


@dataclass
class CanvasConfig:
    width: int = 1600
    height: int = 900
    background: tuple = (0.96, 0.95, 0.92)
    undo_depth: int = 24
    autosave_interval: float = 120.0


@dataclass
class AppConfig:
    orientation: OrientationConfig = field(default_factory=OrientationConfig)
    shake: ShakeConfig = field(default_factory=ShakeConfig)
    spray: SprayConfig = field(default_factory=SprayConfig)
    canvas: CanvasConfig = field(default_factory=CanvasConfig)

    fullscreen: bool = False
    target_fps: int = 120
    debug_overlay: bool = False


